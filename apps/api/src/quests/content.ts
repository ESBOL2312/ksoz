// Контент квестов. Проверяет носитель (владелец проекта): правьте тексты здесь.
// Слова и фразы сидятся в таблицу words (по kk, без дублей) — повторение у них общее с обычным режимом.
// В «В жизни» ___ — место пропуска, answer — kk одного из слов квеста.

export interface QuestItemDef {
  kk: string;
  ru: string;
  /** phrase — готовая фраза: в обычном режиме как новое слово не показывается */
  kind: 'word' | 'phrase';
  /** когда это говорят: подсказка Барыса на карточке */
  note?: string;
  /** пример «kk — ru» */
  example?: string;
}

export interface QuestLifeDef {
  situation: string;
  text: string;
  ru: string;
  answer: string;
}

export interface QuestDialogDef {
  who: 'npc' | 'me';
  kk: string;
  ru: string;
}

export interface QuestStepDef {
  titleKk: string;
  titleRu: string;
  intro: string;
  items: QuestItemDef[];
  life: QuestLifeDef[];
  /** только у последнего шага */
  dialog?: QuestDialogDef[];
}

export interface QuestDef {
  slug: string;
  titleKk: string;
  titleRu: string;
  goal: string;
  npc: string;
  steps: QuestStepDef[];
}

